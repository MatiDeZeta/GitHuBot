#!/usr/bin/env node
/**
 * Regenerates src/bot/render/languages.generated.ts from GitHub Linguist's language
 * list (the `linguist-languages` dev dependency), so the `language` theme knows the
 * same colours GitHub shows. Run with `pnpm generate:languages` after bumping it.
 *
 * The output is committed: the bot itself never loads the package at runtime.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const languages = require("linguist-languages");
// The package does not export its package.json, so read it from beside the entry point.
const { version } = JSON.parse(
	readFileSync(join(dirname(require.resolve("linguist-languages")), "package.json"), "utf8"),
);

const OUT = "src/bot/render/languages.generated.ts";

// `repository.language` in a webhook is the Linguist name; keys are lowercased so
// the lookup ignores case. Aliases are not needed: GitHub always sends the name.
const entries = Object.values(languages)
	.filter(
		(language) => typeof language.color === "string" && /^#[0-9a-f]{6}$/i.test(language.color),
	)
	.map((language) => [language.name.toLowerCase(), language.color.slice(1).toLowerCase()])
	.sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([name, hex]) => `\t${JSON.stringify(name)}: 0x${hex},`).join("\n");

writeFileSync(
	OUT,
	`// Generated by scripts/generate-language-colors.mjs from linguist-languages@${version}.
// Do not edit by hand; run \`pnpm generate:languages\` instead.

/** GitHub Linguist colour for each language, keyed by lowercased language name. */
export const LANGUAGE_COLORS: Readonly<Record<string, number>> = {
${body}
};
`,
);

execFileSync("pnpm", ["exec", "biome", "format", "--write", OUT], { stdio: "inherit" });
console.log(`Wrote ${entries.length} language colours to ${OUT}`);
